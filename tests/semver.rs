#[test]
fn legacy_compatibility() {
    let fixtures: Vec<(Vec<String>, i32, String, Option<String>)> =
        serde_json::from_str(LEGACY).expect("fixed legacy fixtures");
    for (args, code, stdout, stderr) in fixtures {
        let mut command = vec!["semver"];
        command.extend(args.iter().map(String::as_str));
        let actual = common::dt(&command);
        assert_eq!(actual.code, code, "{command:?}: {}", actual.err);
        if args.iter().any(|arg| arg == "--json") && !stdout.is_empty() {
            let expected: serde_json::Value = serde_json::from_str(&stdout).expect("legacy JSON");
            let result: serde_json::Value = serde_json::from_str(&actual.out)
                .unwrap_or_else(|error| panic!("{command:?}: {error}: {}", actual.out));
            assert_eq!(result, expected, "{command:?}");
        } else {
            assert_eq!(actual.out, stdout, "{command:?}");
        }
        if let Some(stderr) = stderr {
            assert_eq!(actual.err, stderr, "{command:?}");
        }
    }
}

#[test]
fn alias_outputs_one_json_document() {
    let result = common::dt(&["sv", "compare", "--json", "1.0.0", "2.0.0"]);
    assert_eq!(result.code, 0);
    assert!(result.err.is_empty());
    assert_eq!(
        serde_json::from_str::<serde_json::Value>(&result.out).expect("JSON"),
        serde_json::json!({"a":"1.0.0","b":"2.0.0","result":-1})
    );
}
