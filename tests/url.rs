mod common;
use common::{dt, dt_in, dt_in_dir};
use serde_json::{Value, json};
const FULL: &str = "https://user:s3cret@example.com:8443/a/b?x=1&y=a%20b&x=2+3#frag";
fn doc(url: &str) -> Value {
    let r = dt(&["url", "--json", url]);
    assert_eq!(r.code, 0, "{url}: {}", r.err);
    serde_json::from_str(&r.out).unwrap()
}
#[test]
fn components_masking_and_ordered_query_rows() {
    let r = dt(&["url", FULL]);
    assert_eq!(r.code, 0, "{}", r.err);
    for (label, value) in [
        ("protocol", "https:"),
        ("username", "user"),
        ("password", "***"),
        ("port", "8443"),
        ("origin", "https://example.com:8443"),
    ] {
        assert!(
            r.out
                .lines()
                .any(|l| l.strip_prefix(&format!("{label}:")).is_some_and(|s| s.trim() == value)),
            "{}",
            r.out
        );
    }
    assert!(!r.out.contains("s3cret"));
    let query = r.out.split_once("Query:").unwrap().1;
    assert_eq!(query.trim_end(), "\n  x = 1\n  y = a b\n  x = 2 3");
}
#[test]
fn show_password_defaults_and_omitted_empty_fields() {
    assert!(dt(&["url", "--show-password", FULL]).out.contains("s3cret"));
    let r = dt(&["url", "http://example.com"]);
    assert!(r.out.contains("(default 80)"));
    for absent in ["username", "password", "search", "hash", "Query"] {
        assert!(!r.out.contains(absent));
    }
}
#[test]
fn query_values_and_missing_key() {
    assert_eq!(dt(&["url", "-q", "x", FULL]).out, "1\n2 3\n");
    assert_eq!(dt(&["url", "--query", "y", FULL]).out, "a b\n");
    let r = dt(&["url", "-q", "nope", FULL]);
    assert_eq!(r.code, 1);
    assert!(r.err.contains("nope"));
}
#[test]
fn pretty_json_stdin_and_revealed_password() {
    let r = dt_in(&["url", "--json"], format!("{FULL}\n").as_bytes());
    assert_eq!(r.code, 0, "{}", r.err);
    let d: Value = serde_json::from_str(&r.out).unwrap();
    assert_eq!(r.out, format!("{}\n", serde_json::to_string_pretty(&d).unwrap()));
    assert_eq!(d["password"], "***");
    assert_eq!(d["hostname"], "example.com");
    assert_eq!(d["port"], "8443");
    assert_eq!(d["pathname"], "/a/b");
    assert_eq!(d["hash"], "#frag");
    assert_eq!(d["query"], json!([["x", "1"], ["y", "a b"], ["x", "2 3"]]));
    let r = dt(&["url", "--json", "--show-password", FULL]);
    assert_eq!(serde_json::from_str::<Value>(&r.out).unwrap()["password"], "s3cret");
}
#[test]
fn incompatible_options_and_invalid_url() {
    assert_eq!(dt(&["url", "--json", "-q", "x", FULL]).code, 2);
    let r = dt(&["url", "example.com/path"]);
    assert_eq!(r.code, 1);
    assert!(r.err.contains("URL tidak valid: example.com/path") && r.err.contains("https://"));
    let r = dt(&["url", "http://"]);
    assert_eq!(r.code, 1);
    assert!(r.err.contains("URL tidak valid: http://"));
}
#[test]
fn invalid_url_credentials_are_always_redacted() {
    for url in [
        "https://user:SECRETPW@exa mple.com/",
        "https://user:SECRETPW@example.com:bad/",
        "https://user:SECRETPW@example.com:65536/",
        "https://user:SECRETPW/extra@exa mple.com/",
        "https://user:SECRETPW?extra@exa mple.com/",
        "https://user:SECRETPW#extra@exa mple.com/",
        "//user:SECRETPW@exa mple.com/",
    ] {
        for opts in [vec![], vec!["--show-password"], vec!["--json"]] {
            let mut a = vec!["url"];
            a.extend(opts);
            a.push(url);
            let r = dt(&a);
            assert_eq!(r.code, 1, "{url}");
            assert!(r.out.is_empty());
            assert!(!r.err.contains("SECRETPW") && !r.err.contains("user:"));
            assert!(r.err.contains("***@"));
        }
    }
}
#[test]
fn opaque_url_and_file_input() {
    let d = doc("mailto:user@example.com");
    assert_eq!(d["pathname"], "user@example.com");
    assert_eq!(d["username"], "");
    assert_eq!(d["password"], "");
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(dir.path().join("url.txt"), FULL).unwrap();
    let r = dt_in_dir(&["url", "--file", "url.txt", "--json"], b"", &[], Some(dir.path()));
    assert_eq!(r.code, 0, "{}", r.err);
    assert_eq!(serde_json::from_str::<Value>(&r.out).unwrap(), doc(FULL));
}
#[test]
fn fixed_legacy_unicode_idna_and_whatwg_vectors() {
    // Captured from the legacy WHATWG URL implementation, not generated by Rust.
    for (url, host, path, origin) in [
        (
            "https://ＦＯＯ。ＥＸＡＭＰＬＥ/é?q=%FF&x=a+b",
            "foo.example",
            "/%C3%A9",
            "https://foo.example",
        ),
        ("https://faß.de/", "xn--fa-hia.de", "/", "https://xn--fa-hia.de"),
        (
            "http://e\u{301}xample.com/",
            "xn--xample-9ua.com",
            "/",
            "http://xn--xample-9ua.com",
        ),
        ("http://☃.net/", "xn--n3h.net", "/", "http://xn--n3h.net"),
        ("http://xn--/", "xn--", "/", "http://xn--"),
        ("http://xn--a/", "xn--a", "/", "http://xn--a"),
        ("http://0x7f.1/", "127.0.0.1", "/", "http://127.0.0.1"),
        ("file:///C|/a/../../b", "", "/C:/b", "null"),
        (
            "blob:https://example.com/id",
            "",
            "https://example.com/id",
            "https://example.com",
        ),
        (
            "http://[2001:db8:0:0:1:0:0:1]/",
            "[2001:db8::1:0:0:1]",
            "/",
            "http://[2001:db8::1:0:0:1]",
        ),
        ("custom://é/a", "%C3%A9", "/a", "null"),
        ("data:text/plain,hello", "", "text/plain,hello", "null"),
        ("http://a/a^b", "a", "/a%5Eb", "http://a"),
    ] {
        let d = doc(url);
        assert_eq!(d["hostname"], host, "{url}");
        assert_eq!(d["pathname"], path, "{url}");
        assert_eq!(d["origin"], origin, "{url}");
    }
    let d = doc("https://ＦＯＯ。ＥＸＡＭＰＬＥ/é?q=%FF&x=a+b");
    assert_eq!(d["query"], json!([["q", "�"], ["x", "a b"]]));
    for url in [
        "http://a\u{200c}b.com/",
        "http://a b/",
        "http://1.2.3.4.5/",
        "http://xn--abc-.é/",
    ] {
        assert_eq!(dt(&["url", "--json", url]).code, 1, "{url}");
    }
    let d = doc("https://u:p@EXAMPLE.com:443/a/../b?x=1&x=2#");
    assert_eq!(d["host"], "example.com");
    assert_eq!(d["port"], "");
    assert_eq!(d["pathname"], "/b");
    assert_eq!(d["hash"], "");
    assert_eq!(d["query"], json!([["x", "1"], ["x", "2"]]));
}

#[test]
fn file_drive_letters_new_path_encoding_and_javascript_whitespace() {
    for (input, path) in [
        ("file:///c|", "/c:"),
        ("file:///C|/a/../b", "/C:/b"),
        ("file:///tmp/C|/x", "/tmp/C|/x"),
    ] {
        assert_eq!(doc(input)["pathname"], path);
    }
    let d = doc("http://u^:p^@a/");
    assert_eq!(d["username"], "u%5E");
    let r = dt(&["url", "--json", "--show-password", "http://u^:p^@a/"]);
    assert_eq!(serde_json::from_str::<Value>(&r.out).unwrap()["password"], "p%5E");
    assert_eq!(doc("\u{feff}https://a/\u{feff}")["hostname"], "a");
}
